// Host function: returns the max batch size for the current arch+type at runtime.
int get_mmvq_mmid_max_batch(ggml_type type, int cc) {
    // NVIDIA: P100, Volta, Ada Lovelace, and Blackwell always use MMVQ for MUL_MAT_ID.
    if (GGML_CUDA_CC_IS_NVIDIA(cc)) {
        cc = ggml_cuda_highest_compiled_arch(cc);
        if (cc == GGML_CUDA_CC_PASCAL || cc == GGML_CUDA_CC_VOLTA || cc >= GGML_CUDA_CC_ADA_LOVELACE) {
            return MMVQ_MAX_BATCH_SIZE;
        }
        if (cc >= GGML_CUDA_CC_TURING) {
            return get_mmvq_mmid_max_batch_turing_plus(type);
        }
        return get_mmvq_mmid_max_batch_pascal_older(type);
    }

    // AMD
    if (GGML_CUDA_CC_IS_AMD(cc)) {
        if (GGML_CUDA_CC_IS_RDNA4(cc)) {
            return get_mmvq_mmid_max_batch_rdna4(type);
        }
        if (GGML_CUDA_CC_IS_RDNA3(cc) || GGML_CUDA_CC_IS_RDNA4_M(cc)) {
            return get_mmvq_mmid_max_batch_rdna3(type);
        }
        if (GGML_CUDA_CC_IS_RDNA1(cc) || GGML_CUDA_CC_IS_RDNA2(cc)) {
            return get_mmvq_mmid_max_batch_rdna1_rdna2(type);
        }
        if (GGML_CUDA_CC_IS_CDNA(cc)) {
            return get_mmvq_mmid_max_batch_cdna(type);
        }
        if (GGML_CUDA_CC_IS_GCN(cc)) {
            return get_mmvq_mmid_max_batch_gcn(type);
        }
    }
    return MMVQ_MAX_BATCH_SIZE;
}

bool ggml_cuda_should_use_mmvq(enum ggml_type type, int cc, int64_t ne11) {
    if (!ggml_is_quantized(type)) {
        return false;
    }
    // k-quants cost more to decode and mvq redoes that per column, so MMQ wins sooner.
    // Only list quant-types MMQ supports, others would fall back to cuBLAS.
    if (GGML_CUDA_CC_IS_NVIDIA(cc) && cc == GGML_CUDA_CC_ADA_LOVELACE) {
        switch (type) { // tuned on RTX 4090
            case GGML_TYPE_Q2_K:
                return ne11 <= 4;
            case GGML_TYPE_Q3_K:
                return ne11 <= 6;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    if (GGML_CUDA_CC_IS_NVIDIA(cc) && cc == GGML_CUDA_CC_BLACKWELL) {
        switch (type) { // tuned on RTX 5090
            case GGML_TYPE_Q2_K:
            case GGML_TYPE_Q3_K:
            case GGML_TYPE_Q4_K:
                return ne11 <= 5;
            case GGML_TYPE_Q5_K:
                return ne11 <= 6;
            case GGML_TYPE_Q6_K:
                return ne11 <= 7;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    if (GGML_CUDA_CC_IS_NVIDIA(cc) && cc == GGML_CUDA_CC_GB10) {
        switch (type) { // tuned on DGX Spark GB10
            case GGML_TYPE_Q2_K:
                return ne11 <= 6;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    if (GGML_CUDA_CC_IS_NVIDIA(cc) && cc == GGML_CUDA_CC_ORIN) {
        switch (type) { // tuned for Jetson Orin
            case GGML_TYPE_Q2_K:
            case GGML_TYPE_Q3_K:
            case GGML_TYPE_Q4_K:
            case GGML_TYPE_Q5_K:
            case GGML_TYPE_Q6_K:
                return ne11 <= 1;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    if (GGML_CUDA_CC_IS_NVIDIA(cc) && cc == GGML_CUDA_CC_VOLTA) {
        switch (type) {
            case GGML_TYPE_Q2_K:
                return ne11 <= 4;
            case GGML_TYPE_Q3_K:
                return ne11 <= 6;
            case GGML_TYPE_Q4_K:
                return ne11 <= 5;
            case GGML_TYPE_Q5_K:
                return ne11 <= 6;
            case GGML_TYPE_Q6_K:
                return ne11 <= 7;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    if (GGML_CUDA_CC_IS_RDNA3_5(cc)) {
        switch (type) { // tuned on Radeon 8060S (gfx1151)
            case GGML_TYPE_Q8_0:
                return ne11 <= 6;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    if (GGML_CUDA_CC_IS_CDNA(cc)) {
        if (GGML_CUDA_CC_IS_CDNA1(cc)) {
            switch (type) {
                case GGML_TYPE_Q4_0:
                case GGML_TYPE_Q4_1:
                    return ne11 <= 7;
                case GGML_TYPE_Q5_1:
                    return ne11 <= 7;
                case GGML_TYPE_Q8_0:
                    return ne11 <= 6;
                case GGML_TYPE_Q2_K:
                    return ne11 <= 4;
                case GGML_TYPE_Q3_K:
                    return ne11 <= 3;
                case GGML_TYPE_Q4_K:
                    return ne11 <= 2;
                case GGML_TYPE_Q5_K:
                    return ne11 <= 3;
                case GGML_TYPE_Q6_K:
                    return ne11 <= 4;
                case GGML_TYPE_IQ1_S:
                case GGML_TYPE_IQ1_XS:
                case GGML_TYPE_IQ1_XXS:
                case GGML_TYPE_IQ1_XXXS:
                    return ne11 <= 5;
                case GGML_TYPE_IQ2_XXS:
                case GGML_TYPE_IQ3_S:
                case GGML_TYPE_IQ4_XS:
                    return ne11 <= 6;
                default:
                    return ne11 <= MMVQ_MAX_BATCH_SIZE;
            }
        }
        switch (type) { // tuned for CDNA2
            case GGML_TYPE_Q2_K:
                return ne11 <= 5;
            case GGML_TYPE_Q3_K:
            case GGML_TYPE_Q4_K:
            case GGML_TYPE_Q5_K:
                return ne11 <= 3;
            case GGML_TYPE_Q6_K:
                return ne11 <= 5;
            default:
                return ne11 <= MMVQ_MAX_BATCH_SIZE;
        }
    }
    return ne11 <= MMVQ_MAX_BATCH_SIZE;
}

// Device constexpr: returns the max batch size for the current arch+type at compile time.
template <ggml_type type>
static constexpr __device__ int get_mmvq_mmid_max_batch_for_device() {
#if defined(RDNA4)
    return get_mmvq_mmid_max_batch_rdna4(type);
#elif defined(RDNA3) || defined(RDNA4_M)
    return get_mmvq_mmid_max_batch_rdna3(type);
#elif defined(RDNA2) || defined(RDNA1)
    return get_mmvq_mmid_max_batch_rdna1_rdna2(type);
#elif defined(CDNA)
    return get_mmvq_mmid_max_batch_cdna(type);
#elif defined(GCN)
    return get_mmvq_mmid_max_batch_gcn(type);
#elif !defined(GGML_USE_MUSA) && (__CUDA_ARCH__ == GGML_CUDA_CC_PASCAL || __CUDA_ARCH__ == GGML_CUDA_CC_VOLTA || __CUDA_ARCH__ >= GGML_CUDA_CC_ADA_LOVELACE)
    return MMVQ_MAX_BATCH_SIZE;
#elif !defined(GGML_USE_MUSA) && __CUDA_ARCH__ >= GGML_CUDA_CC_TURING
    return get_mmvq_mmid_max_batch_turing_plus(type);
#else
    return get_mmvq_mmid_max_batch_pascal_older(type);
#endif
}

static constexpr __host__ __device__ int calc_nwarps(ggml_type type, int ncols_dst, mmvq_parameter_table_id table_id, bool small_k = false, bool halve_iters = false) {
    if (table_id == MMVQ_PARAMETERS_GENERIC) {
        switch (ncols_dst) {
            case 1:
            case 2:
            case 3:
            case 4:
                return 4;
            case 5:
            case 6:
            case 7:
            case 8:
                return 2;
            default:
                return 1;
        }
    } else if (table_id == MMVQ_PARAMETERS_GCN) {
        switch (ncols_dst) {
            case 1:
                return 2;
            case 2:
            case 3:
                return type == GGML_TYPE_Q3_K ? 1 : 2;
            case 4:
                return type == GGML_TYPE_Q6_K? 1 : 2;
            case 5:
            case 6:
            case 7:
            case 8:
            default:
                return 1;
        }
    }
    if (table_id == MMVQ_PARAMETERS_RDNA4) {
        // nwarps=8 benefits types with simple vec_dot on RDNA4 (ncols_dst=1).
        // Types with complex vec_dot (Q3_K, IQ2_*, IQ3_*) regress due to register
        // pressure and lookup table contention at higher thread counts.
        if (ncols_dst == 1) {
            switch (type) {
                case GGML_TYPE_Q4_0:
                case GGML_TYPE_Q4_1:
                case GGML_TYPE_Q5_0:
                case GGML_TYPE_Q5_1:
                case GGML_TYPE_Q8_0:
                case GGML_TYPE_Q2_K:
                case GGML_TYPE_Q4_K:
                case GGML_TYPE_Q5_K:
                case GGML_TYPE_Q6_K:
                case GGML_TYPE_IQ4_NL:
                case GGML_TYPE_IQ4_XS:
                    return 8;
                default:
                    return 1;
            }
        }
        return 1;
    }
    if (table_id == MMVQ_PARAMETERS_RDNA3_0) {
        // RDNA3 (W7900): stricter whitelist than RDNA4.
        // Q2_K / Q5_K / IQ4_XS regress in full quant sweeps.
        if (ncols_dst == 1) {
            switch (type) {
                case GGML_TYPE_Q4_0:
                case GGML_TYPE_Q4_1:
                case GGML_TYPE_Q5_0:
                case GGML_TYPE_Q5_1:
                case GGML_TYPE_Q8_0:
                    return 8;
                case GGML_TYPE_Q6_K:
                    return 2;
                case GGML_TYPE_IQ4_NL:
                    return 8;
                default:
                    return 1;
            }
        }
        return 1;
    }
    if (table_id == MMVQ_PARAMETERS_TURING) {
        if (ncols_dst == 1) {
            switch (type) {
                case GGML_TYPE_Q2_K:
                case GGML_TYPE_Q3_K:
                case GGML_TYPE_Q4_K:
                case GGML_TYPE_Q5_K:
                case GGML_TYPE_Q6_K:
                    return 2;
                default:
                    return 4;
            }
        }
        switch (ncols_dst) {
            case 2:
            case 3:
            case 4:
                return 4;
            case 5:
            case 6:
            case 7:
            case 8:
                return 2;
            default:
                return 1;
        }
    }
    if (table_id == MMVQ_PARAMETERS_GB10) {
        const int generic = calc_nwarps(type, ncols_dst, MMVQ_PARAMETERS_GENERIC);
        // Only worth the wider block when it actually retires the K loop in half the trips (Observation)
        if (ncols_dst == 1 && !small_k && halve_iters) {
            switch (type) {
                case GGML_TYPE_Q4_0:
                case GGML_TYPE_Q4_1:
                case GGML_TYPE_Q5_0:
                case GGML_TYPE_Q5_1:
                case GGML_TYPE_Q8_0:
                case GGML_TYPE_Q4_K:
                case GGML_TYPE_Q5_K:
                case GGML_TYPE_Q6_K:
                case GGML_TYPE_IQ4_NL:
                    return 2 * generic;
                default:
                    break;
            }
        }
        return generic;
    }
    if (table_id == MMVQ_PARAMETERS_ORIN) {
        return calc_nwarps(type, ncols_dst, MMVQ_PARAMETERS_GENERIC);
    }
    return 1;
}

// Low bit types load few weight bytes per thread, a second row per block shares the q8_1 loads and adds memory parallelism.
static constexpr __host__ __device__ bool mmvq_two_rows_ncols1(ggml_type type) {
    switch (type) {
        case GGML_TYPE_Q1_0:
        case GGML_TYPE_Q2_K:
        case GGML_TYPE_Q3_K:
        case GGML_TYPE_IQ1_S:
        case GGML_TYPE_IQ1_M:
            return true;
        default:
            return false;
    }
}

static constexpr __host__ __device__ int calc_rows_per_block(ggml_type type, int ncols_dst, int table_id, bool small_k = false, int nwarps = 1) {
    if (table_id == MMVQ_PARAMETERS_GENERIC || table_id == MMVQ_PARAMETERS_GCN || table_id == MMVQ_PARAMETERS_TURING || table_id == MMVQ_PARAMETERS_GB10) {
        switch (ncols_dst) {
            case 1:
                if (small_k) {
                    return nwarps;
                }
                if (table_id == MMVQ_PARAMETERS_GB10) {
                    return type == GGML_TYPE_IQ2_S || type == GGML_TYPE_IQ3_S ? 2 : 1;
                }
                return table_id == MMVQ_PARAMETERS_GENERIC && mmvq_two_rows_ncols1(type) ? 2 : 1;
            case 2:
            case 3:
            case 4:
            case 5:
            case 6:
            case 7:
            case 8:
                return 2;
            default:
                return 1;
        }
    }
    if (table_id == MMVQ_PARAMETERS_ORIN) {
        switch (ncols_dst) {
            case 1:
                if (small_k) {
                    return nwarps;
                }
                // One row per warp (more rows per block, more loads in flight) for these types, measured on Jetson Orin Nano.
                // Other types are faster in isolated mat-vec too, but gained at most 2 % end to end.
                switch (type) {
                    case GGML_TYPE_Q4_0:
                    case GGML_TYPE_Q4_1:
                    case GGML_TYPE_Q5_0:
                    case GGML_TYPE_Q5_1:
                    case GGML_TYPE_Q8_0:
                    case GGML_TYPE_Q4_K:
                    case GGML_TYPE_Q5_K:
                    case GGML_TYPE_Q6_K:
                    case GGML_TYPE_IQ4_NL:
                        return nwarps;
                    default:
                        break;
                }
                return mmvq_two_rows_ncols1(type) ? 2 : 1;
            case 2:
            case 3:
            case 4:
            case 5:
            case 6:
            case 7:
            case 8:
                return 2;
            default:
                return 1;
        }
    }
    return 1;
}

// AMB_FUSE_SHEXP_MT (C20): amb_post = true appends the epilogue dst = post_add + result * sigmoid(post_sig[j])
// (shared-expert down projection, gate sigmoid, MUL and residual ADD). It is only instantiated with
// has_fusion = false, so the dot products and their reduction are the code of the plain kernel.
template <ggml_type type, int ncols_dst, bool has_fusion, bool small_k = false, bool halve_iters = false, bool amb_post = false>
__launch_bounds__(calc_nwarps(type, ncols_dst, get_device_table_id(), small_k, halve_iters)*ggml_cuda_get_physical_warp_size(), 1)
static __global__ void mul_mat_vec_q(
        const void * vx_ptr, const void * vy_ptr, const int32_t * ids_ptr, const ggml_cuda_mm_fusion_args_device fusion, float * dst_ptr,
        const uint32_t ncols_x, const uint3 nchannels_y, const uint32_t stride_row_x, const uint32_t stride_col_y,
        uint32_t stride_col_dst, const uint3 channel_ratio, const uint32_t stride_channel_x,
        const uint32_t stride_channel_y, const uint32_t stride_channel_dst, const uint3 sample_ratio,
        const uint32_t stride_sample_x, const uint32_t stride_sample_y, const uint32_t stride_sample_dst,
        const uint32_t ids_stride) {
    const void    * GGML_CUDA_RESTRICT vx  = vx_ptr;
    const void    * GGML_CUDA_RESTRICT vy  = vy_ptr;
    const int32_t * GGML_CUDA_RESTRICT ids = ids_ptr;
    float         * GGML_CUDA_RESTRICT dst = dst_ptr;

    constexpr int qk  = ggml_cuda_type_traits<type>::qk;
    constexpr int qi  = ggml_cuda_type_traits<type>::qi;
    constexpr int vdr = get_vdr_mmvq(type);
    constexpr mmvq_parameter_table_id table_id = get_device_table_id();
    constexpr int nwarps = calc_nwarps(type, ncols_dst, table_id, small_k, halve_iters);
    constexpr int rows_per_cuda_block = calc_rows_per_block(type, ncols_dst, table_id, small_k, nwarps);
    constexpr int warp_size = ggml_cuda_get_physical_warp_size();

    constexpr vec_dot_q_cuda_t vec_dot_q_cuda = get_vec_dot_q_cuda(type);

    const     int tid = warp_size*threadIdx.y + threadIdx.x;
    const     int row0 = rows_per_cuda_block*blockIdx.x;
    const     int blocks_per_row_x = ncols_x / qk;
    constexpr int blocks_per_iter = vdr * nwarps*warp_size / qi;

    const bool shared_expert = has_fusion && fusion.shared_up && blockIdx.y == gridDim.y - 1;
    const uint32_t channel_dst = shared_expert ? 0 : blockIdx.y;
    if (shared_expert) {
        vx = fusion.shared_up;
        dst = fusion.shared_dst;
        stride_col_dst = fusion.shared_stride_col_dst;
    }

    uint32_t channel_x;
    uint32_t channel_y;
    uint32_t sample_dst;

    ggml_cuda_pdl_sync();
    channel_x  = shared_expert ? 0 : ncols_dst == 1 && ids ? ids[channel_dst] : fastdiv(channel_dst, channel_ratio);
    channel_y  = ncols_dst == 1 && ids ? fastmodulo(channel_dst, nchannels_y) : channel_dst;
    sample_dst = blockIdx.z;

    const uint32_t sample_x    = fastdiv(sample_dst, sample_ratio);
    const uint32_t sample_y    = sample_dst;

    bool use_gate = false;
    bool use_bias = false;
    bool use_gate_bias = false;
    bool use_scale = false;
    bool use_gate_scale = false;
    [[maybe_unused]] const void * vgate = nullptr;
    const float * x_bias = nullptr;
    const float * gate_bias = nullptr;
    const float * x_scale = nullptr;
    const float * gate_scale = nullptr;
    ggml_glu_op active_glu;
    float glu_limit = 0.0f;

    if constexpr (has_fusion) {
        use_gate      = fusion.gate      != nullptr;
        use_bias      = fusion.x_bias    != nullptr;
        use_gate_bias = fusion.gate_bias != nullptr && use_gate;
        vgate         = shared_expert ? fusion.shared_gate : fusion.gate;
        x_bias        = (const float *) fusion.x_bias;
        gate_bias     = (const float *) fusion.gate_bias;
        active_glu    = fusion.glu_op;
        glu_limit     = fusion.glu_limit;
        if constexpr (type == GGML_TYPE_NVFP4) {
            use_scale      = fusion.x_scale    != nullptr;
            use_gate_scale = fusion.gate_scale != nullptr && use_gate;
            x_scale        = (const float *) fusion.x_scale;
            gate_scale     = (const float *) fusion.gate_scale;
        }
    }


    [[maybe_unused]] float x_biases[ncols_dst]    = { 0.0f };
    [[maybe_unused]] float gate_biases[ncols_dst] = { 0.0f };
    [[maybe_unused]] float x_scales = 1.0f;
    [[maybe_unused]] float gate_scales = 1.0f;
    if constexpr (has_fusion) {
        // 1. Hide latency by prefetching bias, gates and scales here
        // 2. load only on threads that won't die after partial sum calculation
        const uint32_t channel_bias = ids ? channel_x : channel_dst;
        if (threadIdx.x < rows_per_cuda_block && threadIdx.y == 0 &&
            (rows_per_cuda_block == 1 || uint32_t(row0 + threadIdx.x) < stride_col_dst)) {
            if (use_bias) {
                x_bias = x_bias + sample_dst * stride_sample_dst + channel_bias * stride_channel_dst + row0;
#pragma unroll
                for (int j = 0; j < ncols_dst; ++j) {
                    x_biases[j] = x_bias[j * stride_col_dst + threadIdx.x];
                }
            }
            if (use_gate_bias) {
                gate_bias = gate_bias + sample_dst * stride_sample_dst + channel_bias * stride_channel_dst + row0;
#pragma unroll
                for (int j = 0; j < ncols_dst; ++j) {
                    gate_biases[j] = gate_bias[j * stride_col_dst + threadIdx.x];
                }
            }
            if constexpr (type == GGML_TYPE_NVFP4) {
                if (use_scale) {
                    x_scales = x_scale[ids ? channel_x : 0];
                }
                if (use_gate_scale) {
                    gate_scales = gate_scale[ids ? channel_x : 0];
                }
            }
        }
    }

    // partial sum for each thread
    float tmp[ncols_dst][rows_per_cuda_block] = {{0.0f}};
    float tmp_gate[ncols_dst][rows_per_cuda_block] = {{0.0f}};

    const block_q8_1 * y = ((const block_q8_1 *) vy) + sample_y*stride_sample_y + channel_y*stride_channel_y;
    const int64_t kbx_offset = int64_t(sample_x)*stride_sample_x + int64_t(channel_x)*stride_channel_x + int64_t(row0)*stride_row_x;

    for (int kbx = tid / (qi/vdr); kbx < blocks_per_row_x; kbx += blocks_per_iter) {
        const int kby = kbx * (qk/QK8_1); // y block index that aligns with kbx

        // x block quant index when casting the quants to int
        const int kqs = vdr * (tid % (qi/vdr));

#if __CUDA_ARCH__ == GGML_CUDA_CC_GB10
        // start the next iterations' weight loads early
        if constexpr (mmvq_should_prefetch(type)) {
            // loop iterations, not blocks; q3_K and q6_K keep the distance in blocks they had with vdr 1
            constexpr int pf_dist = type == GGML_TYPE_Q3_K || type == GGML_TYPE_Q6_K ? 1 : 2;
            const int kbx_pf = kbx + pf_dist*blocks_per_iter;
            if (kbx_pf < blocks_per_row_x) {
#pragma unroll
                for (int i = 0; i < rows_per_cuda_block; ++i) {
                    const size_t off = (size_t)(kbx_offset + i*stride_row_x + kbx_pf) * ggml_cuda_type_traits<type>::bs;
                    ggml_cuda_prefetch_l2((const char *) vx + off);
                    if constexpr (has_fusion) {
                        if (use_gate) {
                            ggml_cuda_prefetch_l2((const char *) vgate + off);
                        }
                    }
                }
            }
        }
#endif

#pragma unroll
        for (int j = 0; j < ncols_dst; ++j) {
#pragma unroll
            for (int i = 0; i < rows_per_cuda_block; ++i) {
                tmp[j][i] += vec_dot_q_cuda(
                    vx, &y[j*stride_col_y + kby], kbx_offset + i*stride_row_x + kbx, kqs);
                if constexpr (has_fusion) {
                    if (use_gate) {
                        tmp_gate[j][i] += vec_dot_q_cuda(
                            vgate, &y[j*stride_col_y + kby], kbx_offset + i*stride_row_x + kbx, kqs);
                    }
                }
            }
        }
    }

    __shared__ float tmp_shared[nwarps-1 > 0 ? nwarps-1 : 1][ncols_dst][rows_per_cuda_block][warp_size];
    [[maybe_unused]] __shared__ float tmp_shared_gate[(has_fusion && (nwarps-1 > 0)) ? nwarps-1 : 1][ncols_dst][rows_per_cuda_block][warp_size];

    if (threadIdx.y > 0) {
#pragma unroll
        for (int j = 0; j < ncols_dst; ++j) {
#pragma unroll
            for (int i = 0; i < rows_per_cuda_block; ++i) {
                tmp_shared[threadIdx.y-1][j][i][threadIdx.x] = tmp[j][i];
                if constexpr (has_fusion) {
                    if (use_gate) {
                        tmp_shared_gate[threadIdx.y-1][j][i][threadIdx.x] = tmp_gate[j][i];
                    }
                }
            }
        }
    }
    __syncthreads();
    if (threadIdx.y > 0) {
        return;
    }

    dst += sample_dst*stride_sample_dst + channel_dst*stride_channel_dst + row0;

    // sum up partial sums and write back result
#pragma unroll
    for (int j = 0; j < ncols_dst; ++j) {
#pragma unroll
        for (int i = 0; i < rows_per_cuda_block; ++i) {
#pragma unroll
            for (int l = 0; l < nwarps-1; ++l) {
                tmp[j][i] += tmp_shared[l][j][i][threadIdx.x];
                if constexpr (has_fusion) {
                    if (use_gate) {
                        tmp_gate[j][i] += tmp_shared_gate[l][j][i][threadIdx.x];
                    }
                }
            }
            tmp[j][i] = warp_reduce_sum<warp_size>(tmp[j][i]);
            if constexpr (has_fusion) {
                if (use_gate) {
                    tmp_gate[j][i] = warp_reduce_sum<warp_size>(tmp_gate[j][i]);
                }
            }

            if (threadIdx.x == i && (rows_per_cuda_block == 1 || uint32_t(row0 + i) < stride_col_dst)) {
                float result = tmp[j][i];
                if constexpr (has_fusion) {
                    if constexpr (type == GGML_TYPE_NVFP4) {
                        result *= x_scales;
                    }
                    result += x_biases[j];
                    if (use_gate) {
                        float gate_value = tmp_gate[j][i];
                        if constexpr (type == GGML_TYPE_NVFP4) {
                            gate_value *= gate_scales;
                        }
                        gate_value += gate_biases[j];
                        switch (active_glu) {
                            case GGML_GLU_OP_SWIGLU:
                                result *= ggml_cuda_op_silu_single(gate_value);
                                break;
                            case GGML_GLU_OP_GEGLU:
                                result *= ggml_cuda_op_gelu_single(gate_value);
                                break;
                            case GGML_GLU_OP_SWIGLU_OAI:
                                result = ggml_cuda_op_swiglu_oai_single(gate_value, result);
                                break;
                            case GGML_GLU_OP_SWIGLU_CLAMP:
                                result = ggml_cuda_op_swiglu_clamp_single(gate_value, result, glu_limit);
                                break;
                            default:
                                result = result * gate_value;
                                break;
                        }
                    }
                }
                if constexpr (amb_post) {
                    // Same expressions as the unfused SIGMOID (unary.cu op_sigmoid), MUL (op_mul: a*b) and ADD
                    // (op_add: a+b) kernels. __fmul_rn/__fadd_rn are never contracted into an FMA and honour -ftz
                    // like the plain operators there, so each step rounds exactly as the separate kernels do.
                    const float sg  = fusion.amb_post_sig[j];
                    const float sig = 1.0f / (1.0f + expf(-sg));
                    result = __fmul_rn(result, sig);
                    result = __fadd_rn(fusion.amb_post_add[j*stride_col_dst + row0 + i], result);
                }
                dst[j*stride_col_dst + i] = result;
            }
        }
    }

    if constexpr (!has_fusion) {
        GGML_UNUSED_VARS(use_gate, use_bias, use_gate_bias, use_scale, use_gate_scale, active_glu, glu_limit, gate_bias, x_bias, x_scale, gate_scale, tmp_gate);
    }
    if constexpr (type != GGML_TYPE_NVFP4) {
        GGML_UNUSED_VARS(use_scale, use_gate_scale, x_scale, gate_scale, x_scales, gate_scales);
    }
}

// Dedicated MoE multi-token kernel.
// Grid: (ceil(nrows_x / c_rows_per_block), nchannels_dst)
// Block: (warp_size, ncols_dst) - each warp handles one token independently.
// No shared memory reduction needed since each warp works alone.
// masked (AMB_MOE_MISS_OVERLAP=2, C24): an id < 0 marks a (token, slot) pair that this launch does not compute; its
// warp writes -0.0f to its output rows (x + -0.0f == x for every x, so the caller can merge two launches with one ADD)
// and reads no weights. masked = false compiles exactly the code of before (the masked branch is if constexpr)
template <ggml_type type, int c_rows_per_block, bool has_fusion = false, bool masked = false>
__launch_bounds__(get_mmvq_mmid_max_batch_for_device<type>()*ggml_cuda_get_physical_warp_size(), 1)
static __global__ void mul_mat_vec_q_moe(
        const void * vx_ptr, const void * vy_ptr, const int32_t * ids_ptr, const ggml_cuda_mm_fusion_args_device fusion,
        float * dst_ptr,
        const uint32_t ncols_x, const uint3 nchannels_y, const uint32_t nrows_x,
        const uint32_t stride_row_x, const uint32_t stride_col_y, uint32_t stride_col_dst,
        const uint32_t stride_channel_x, const uint32_t stride_channel_y, const uint32_t stride_channel_dst,
        const uint32_t ncols_dst, const uint32_t ids_stride) {
    const void    * GGML_CUDA_RESTRICT vx  = vx_ptr;
    const void    * GGML_CUDA_RESTRICT vy  = vy_ptr;
    const int32_t * GGML_CUDA_RESTRICT ids = ids_ptr;
    float         * GGML_CUDA_RESTRICT dst = dst_ptr;

    constexpr int qk  = ggml_cuda_type_traits<type>::qk;
    constexpr int qi  = ggml_cuda_type_traits<type>::qi;
    constexpr int vdr = get_vdr_mmvq(type);
    constexpr int warp_size = ggml_cuda_get_physical_warp_size();

    constexpr vec_dot_q_cuda_t vec_dot_q_cuda = get_vec_dot_q_cuda(type);

    const bool shared_expert = has_fusion && fusion.shared_up && blockIdx.y == gridDim.y - 1;
    if (shared_expert) {
        vx = fusion.shared_up;
        dst = fusion.shared_dst;
        stride_col_dst = fusion.shared_stride_col_dst;
    }

    // fuse gate, bias, scales, and glu_op into the up projection
    bool use_gate = false;
    const void  * vgate      = nullptr;
    const float * x_bias     = nullptr;
    const float * gate_bias  = nullptr;
    const float * x_scale    = nullptr;
    const float * gate_scale = nullptr;
    ggml_glu_op   active_glu = GGML_GLU_OP_SWIGLU;
    float         glu_limit  = 0.0f;

    if constexpr (has_fusion) {
        use_gate   = fusion.gate != nullptr;
        vgate      = shared_expert ? fusion.shared_gate : fusion.gate;
        x_bias     = (const float *) fusion.x_bias;
        gate_bias  = (const float *) fusion.gate_bias;
        active_glu = fusion.glu_op;
        glu_limit  = fusion.glu_limit;
        if constexpr (type == GGML_TYPE_NVFP4) {
            x_scale    = (const float *) fusion.x_scale;
            gate_scale = (const float *) fusion.gate_scale;
        }
    }

    const uint32_t token_idx   = threadIdx.y;
    const int      row0        = c_rows_per_block*blockIdx.x;
    const int      blocks_per_row_x = ncols_x / qk;
    constexpr int  blocks_per_iter  = vdr * warp_size / qi;

    const uint32_t channel_dst = shared_expert ? 0 : blockIdx.y;

    if (token_idx >= ncols_dst) {
        return;
    }

    ggml_cuda_pdl_sync();
    if constexpr (masked) {
        // never with a fused shared expert (checked at launch)
        if (ids[channel_dst + token_idx * ids_stride] < 0) {
            if (threadIdx.x < c_rows_per_block && (c_rows_per_block == 1 || uint32_t(row0 + threadIdx.x) < nrows_x)) {
                dst[channel_dst*stride_channel_dst + token_idx*stride_col_dst + row0 + threadIdx.x] = -0.0f;
            }
            return;
        }
    }
    const uint32_t channel_x = shared_expert ? 0 : ids[channel_dst + token_idx * ids_stride];
    const uint32_t channel_y = fastmodulo(channel_dst, nchannels_y);

    const block_q8_1 * y = ((const block_q8_1 *) vy) + channel_y*stride_channel_y + token_idx*stride_col_y;
    const int64_t kbx_offset  = int64_t(channel_x)*stride_channel_x + int64_t(row0)*stride_row_x;

    // partial sum for each thread
    float tmp[c_rows_per_block] = {0.0f};
    float tmp_gate[c_rows_per_block] = {0.0f};

    for (int kbx = threadIdx.x / (qi/vdr); kbx < blocks_per_row_x; kbx += blocks_per_iter) {
        const int kby = kbx * (qk/QK8_1);
        const int kqs = vdr * (threadIdx.x % (qi/vdr));

#pragma unroll
        for (int i = 0; i < c_rows_per_block; ++i) {
            tmp[i] += vec_dot_q_cuda(vx, &y[kby], kbx_offset + i*stride_row_x + kbx, kqs);
            if constexpr (has_fusion) {
                if (use_gate) {
                    tmp_gate[i] += vec_dot_q_cuda(vgate, &y[kby], kbx_offset + i*stride_row_x + kbx, kqs);
                }
            }
        }
    }

    ggml_cuda_pdl_lc();

    // Warp-level reduction only - no shared memory needed
#pragma unroll
    for (int i = 0; i < c_rows_per_block; ++i) {
        tmp[i] = warp_reduce_sum<warp_size>(tmp[i]);
        if constexpr (has_fusion) {
            if (use_gate) {
                tmp_gate[i] = warp_reduce_sum<warp_size>(tmp_gate[i]);
            }
        }
    }

    // Write results
    if (threadIdx.x < c_rows_per_block && (c_rows_per_block == 1 || uint32_t(row0 + threadIdx.x) < nrows_x)) {
        float result = tmp[threadIdx.x];
        if constexpr (has_fusion) {
            const uint32_t bias_idx = channel_x*stride_channel_dst + row0 + threadIdx.x;

            if constexpr (type == GGML_TYPE_NVFP4) {
                if (x_scale) {
                    // AMB_MOE_SCALE_KERNEL (M6): with scale ids the weights are read by slot (channel_x) and the scale
                    // by the routed expert id; the product is the one the separate MUL node computed
                    const uint32_t scale_idx = fusion.amb_x_scale_ids ?
                        (uint32_t) fusion.amb_x_scale_ids[channel_dst + token_idx * ids_stride] : channel_x;
                    result *= x_scale[scale_idx];
                }
            }
            if (x_bias) {
                result += x_bias[bias_idx];
            }
            if (use_gate) {
                float gate_value = tmp_gate[threadIdx.x];
                if constexpr (type == GGML_TYPE_NVFP4) {
                    if (gate_scale) {
                        gate_value *= gate_scale[channel_x];
                    }
                }
                if (gate_bias) {
                    gate_value += gate_bias[bias_idx];
                }
                switch (active_glu) {
                    case GGML_GLU_OP_SWIGLU:
                        result *= ggml_cuda_op_silu_single(gate_value);
                        break;
                    case GGML_GLU_OP_GEGLU:
                        result *= ggml_cuda_op_gelu_single(gate_value);
                        break;
                    case GGML_GLU_OP_SWIGLU_OAI:
                        result = ggml_cuda_op_swiglu_oai_single(gate_value, result);
                        break;
                    case GGML_GLU_OP_SWIGLU_CLAMP:
                        result = ggml_cuda_op_swiglu_clamp_single(gate_value, result, glu_limit);
                        break;
                    default:
                        result = result * gate_value;
                        break;
                }
            }
        }
        dst[channel_dst*stride_channel_dst + token_idx*stride_col_dst + row0 + threadIdx.x] = result;
    }

    if constexpr (!has_fusion) {
        GGML_UNUSED_VARS(use_gate, tmp_gate, vgate, x_bias, gate_bias, active_glu, glu_limit, x_scale, gate_scale);
    } else if constexpr (type != GGML_TYPE_NVFP4) {
        GGML_UNUSED_VARS(x_scale, gate_scale);
    }
}

// AMB_MOE_GROUPED (G1): expert-grouped variant of mul_mat_vec_q_moe for the weight types amb_moe_grouped_type lists.
// Same grid and block as mul_mat_vec_q_moe (one block per (row pair, slot), one warp per token), but an expert that
// several tokens of the batch selected is read by one warp only: the warp of the first token that uses it (the
// leader) computes the dot products of every later token that selected the same expert (in whatever slot) from the
// weight values it has already loaded, and writes each result to that token's (slot, token) position. The warps of
// the later tokens exit without reading weights.
// Exactness: per (token, slot, row) the partial sums are accumulated per lane over the same kbx sequence with the
// same vec_dot_q_cuda call, reduced with the same warp_reduce_sum and finished with the same epilogue expressions as
// in mul_mat_vec_q_moe; only the warp that runs them differs.
// Grouping (on the device, from ids, no table and no host readback): lane l compares the ids of routes l and l + 32
// (route = slot + token*n_slots, n_slots*n_tokens <= 64 is checked on the host) with the warp's own id, two ballots
// give the 64 bit match mask m. With first = "no lower slot of my token has my id" and earlier = "a lower token has
// my id": first && earlier -> covered by the leader, exit; otherwise compute the own route, and if first also the
// first matching slot of every higher token. This is correct for any ids content (an id repeated inside one token
// is computed by its own warp), ids < 0 are not supported (masked ids keep the stock kernel).
// The fused shared expert (last grid row) is one group of all tokens: the warp of token 0 computes all of them.
static constexpr __host__ __device__ bool amb_moe_grouped_type(ggml_type type) {
    return type == GGML_TYPE_NVFP4 || type == GGML_TYPE_Q8_0;
}

// the epilogue of mul_mat_vec_q_moe (same expressions, same order) for one (token, slot, row) result
template <ggml_type type, bool has_fusion>
static __device__ __forceinline__ float amb_moe_grouped_finish(
        float result, const float gate_sum, const bool use_gate,
        const float * x_bias, const float * gate_bias, const float * x_scale, const float * gate_scale,
        const ggml_glu_op active_glu, const float glu_limit, const uint32_t channel_x, const uint32_t bias_idx) {
    if constexpr (has_fusion) {
        if constexpr (type == GGML_TYPE_NVFP4) {
            if (x_scale) {
                result *= x_scale[channel_x];
            }
        }
        if (x_bias) {
            result += x_bias[bias_idx];
        }
        if (use_gate) {
            float gate_value = gate_sum;
            if constexpr (type == GGML_TYPE_NVFP4) {
                if (gate_scale) {
                    gate_value *= gate_scale[channel_x];
                }
            }
            if (gate_bias) {
                gate_value += gate_bias[bias_idx];
            }
            switch (active_glu) {
                case GGML_GLU_OP_SWIGLU:
                    result *= ggml_cuda_op_silu_single(gate_value);
                    break;
                case GGML_GLU_OP_GEGLU:
                    result *= ggml_cuda_op_gelu_single(gate_value);
                    break;
                case GGML_GLU_OP_SWIGLU_OAI:
                    result = ggml_cuda_op_swiglu_oai_single(gate_value, result);
                    break;
                case GGML_GLU_OP_SWIGLU_CLAMP:
                    result = ggml_cuda_op_swiglu_clamp_single(gate_value, result, glu_limit);
                    break;
                default:
                    result = result * gate_value;
                    break;
            }
        }
    }
    GGML_UNUSED_VARS(gate_sum, use_gate, x_bias, gate_bias, x_scale, gate_scale, active_glu, glu_limit, channel_x, bias_idx);
    return result;
}

template <ggml_type type, int c_rows_per_block, bool has_fusion = false>
__launch_bounds__(MMVQ_MAX_BATCH_SIZE*ggml_cuda_get_physical_warp_size(), 1)
static __global__ void mul_mat_vec_q_moe_grouped(
        const void * vx_ptr, const void * vy_ptr, const int32_t * ids_ptr, const ggml_cuda_mm_fusion_args_device fusion,
        float * dst_ptr,
        const uint32_t ncols_x, const uint3 nchannels_y, const uint32_t nrows_x,
        const uint32_t stride_row_x, const uint32_t stride_col_y, uint32_t stride_col_dst,
        const uint32_t stride_channel_x, const uint32_t stride_channel_y, const uint32_t stride_channel_dst,
        const uint32_t ncols_dst, const uint32_t ids_stride) {
    const void    * GGML_CUDA_RESTRICT vx  = vx_ptr;
    const void    * GGML_CUDA_RESTRICT vy  = vy_ptr;
    const int32_t * GGML_CUDA_RESTRICT ids = ids_ptr;
    float         * GGML_CUDA_RESTRICT dst = dst_ptr;

    constexpr int qk  = ggml_cuda_type_traits<type>::qk;
    constexpr int qi  = ggml_cuda_type_traits<type>::qi;
    constexpr int vdr = get_vdr_mmvq(type);
    constexpr int warp_size = ggml_cuda_get_physical_warp_size();
    constexpr int max_tokens = MMVQ_MAX_BATCH_SIZE;
    static_assert(warp_size == 32, "the route match mask is built from two 32 lane ballots");
    static_assert(max_tokens <= 8, "one accumulator set per token");

    constexpr vec_dot_q_cuda_t vec_dot_q_cuda = get_vec_dot_q_cuda(type);

    const bool has_shared    = has_fusion && fusion.shared_up;
    const bool shared_expert = has_shared && blockIdx.y == gridDim.y - 1;
    if (shared_expert) {
        vx = fusion.shared_up;
        dst = fusion.shared_dst;
        stride_col_dst = fusion.shared_stride_col_dst;
    }

    // fuse gate, bias, scales, and glu_op into the up projection
    bool use_gate = false;
    const void  * vgate      = nullptr;
    const float * x_bias     = nullptr;
    const float * gate_bias  = nullptr;
    const float * x_scale    = nullptr;
    const float * gate_scale = nullptr;
    ggml_glu_op   active_glu = GGML_GLU_OP_SWIGLU;
    float         glu_limit  = 0.0f;

    if constexpr (has_fusion) {
        use_gate   = fusion.gate != nullptr;
        vgate      = shared_expert ? fusion.shared_gate : fusion.gate;
        x_bias     = (const float *) fusion.x_bias;
        gate_bias  = (const float *) fusion.gate_bias;
        active_glu = fusion.glu_op;
        glu_limit  = fusion.glu_limit;
        if constexpr (type == GGML_TYPE_NVFP4) {
            x_scale    = (const float *) fusion.x_scale;
            gate_scale = (const float *) fusion.gate_scale;
        }
    }

    const uint32_t token_idx   = threadIdx.y;
    const int      row0        = c_rows_per_block*blockIdx.x;
    const int      blocks_per_row_x = ncols_x / qk;
    constexpr int  blocks_per_iter  = vdr * warp_size / qi;

    const uint32_t channel_dst = shared_expert ? 0 : blockIdx.y;

    if (token_idx >= ncols_dst) {
        return;
    }

    ggml_cuda_pdl_sync();

    // the other tokens this warp computes: bit t of others, their slot in slot_of[t]
    uint32_t others = 0;
    uint32_t slot_of[max_tokens] = {0};
    uint32_t channel_x = 0;

    if (shared_expert) {
        if (token_idx != 0) {
            return;
        }
        others = ((1u << ncols_dst) - 1u) & ~1u;
    } else {
        channel_x = ids[channel_dst + token_idx * ids_stride];

        const uint32_t n_slots  = gridDim.y - (has_shared ? 1 : 0);
        const uint32_t n_routes = n_slots*ncols_dst; // <= 64 (host)
        const uint32_t r_lo = threadIdx.x;
        const uint32_t r_hi = threadIdx.x + warp_size;
        const bool hit_lo = r_lo < n_routes && uint32_t(ids[r_lo % n_slots + (r_lo / n_slots) * ids_stride]) == channel_x;
        const bool hit_hi = r_hi < n_routes && uint32_t(ids[r_hi % n_slots + (r_hi / n_slots) * ids_stride]) == channel_x;
        const uint64_t m = uint64_t(__ballot_sync(0xFFFFFFFFu, hit_lo)) | (uint64_t(__ballot_sync(0xFFFFFFFFu, hit_hi)) << 32);

        const uint64_t slot_mask = (1ull << n_slots) - 1ull; // n_slots <= 32
        const uint64_t own       = (m >> (token_idx*n_slots)) & slot_mask;
        const bool     first     = (own & ((1ull << channel_dst) - 1ull)) == 0;
        const bool     earlier   = (m & ((1ull << (token_idx*n_slots)) - 1ull)) != 0;
        if (first && earlier) {
            return; // computed by the warp of the first token with this expert
        }
        if (first) {
#pragma unroll
            for (int t = 1; t < max_tokens; ++t) {
                if (uint32_t(t) > token_idx && uint32_t(t) < ncols_dst) {
                    const uint64_t tm = (m >> (uint32_t(t)*n_slots)) & slot_mask;
                    if (tm != 0) {
                        others    |= 1u << t;
                        slot_of[t] = __ffsll((long long) tm) - 1;
                    }
                }
            }
        }
    }

    const uint32_t channel_y = fastmodulo(channel_dst, nchannels_y);

    const block_q8_1 * y = ((const block_q8_1 *) vy) + channel_y*stride_channel_y + token_idx*stride_col_y;
    const int64_t kbx_offset  = int64_t(channel_x)*stride_channel_x + int64_t(row0)*stride_row_x;

    const block_q8_1 * y_o[max_tokens];
#pragma unroll
    for (int t = 0; t < max_tokens; ++t) {
        y_o[t] = ((const block_q8_1 *) vy) + fastmodulo(slot_of[t], nchannels_y)*stride_channel_y + uint32_t(t)*stride_col_y;
    }

    // partial sum for each thread: own route, then one set per other token
    float tmp[c_rows_per_block] = {0.0f};
    float tmp_gate[c_rows_per_block] = {0.0f};
    float tmp_o[max_tokens][c_rows_per_block] = {{0.0f}};
    float tmp_gate_o[max_tokens][c_rows_per_block] = {{0.0f}};

    for (int kbx = threadIdx.x / (qi/vdr); kbx < blocks_per_row_x; kbx += blocks_per_iter) {
        const int kby = kbx * (qk/QK8_1);
        const int kqs = vdr * (threadIdx.x % (qi/vdr));

#pragma unroll
        for (int i = 0; i < c_rows_per_block; ++i) {
            tmp[i] += vec_dot_q_cuda(vx, &y[kby], kbx_offset + i*stride_row_x + kbx, kqs);
            if constexpr (has_fusion) {
                if (use_gate) {
                    tmp_gate[i] += vec_dot_q_cuda(vgate, &y[kby], kbx_offset + i*stride_row_x + kbx, kqs);
                }
            }
#pragma unroll
            for (int t = 1; t < max_tokens; ++t) {
                if (others & (1u << t)) {
                    tmp_o[t][i] += vec_dot_q_cuda(vx, &y_o[t][kby], kbx_offset + i*stride_row_x + kbx, kqs);
                    if constexpr (has_fusion) {
                        if (use_gate) {
                            tmp_gate_o[t][i] += vec_dot_q_cuda(vgate, &y_o[t][kby], kbx_offset + i*stride_row_x + kbx, kqs);
                        }
                    }
                }
            }
        }
    }

    ggml_cuda_pdl_lc();

    // Warp-level reduction only - no shared memory needed
#pragma unroll
    for (int i = 0; i < c_rows_per_block; ++i) {
        tmp[i] = warp_reduce_sum<warp_size>(tmp[i]);
        if constexpr (has_fusion) {
            if (use_gate) {
                tmp_gate[i] = warp_reduce_sum<warp_size>(tmp_gate[i]);
            }
        }
#pragma unroll
        for (int t = 1; t < max_tokens; ++t) {
            if (others & (1u << t)) {
                tmp_o[t][i] = warp_reduce_sum<warp_size>(tmp_o[t][i]);
                if constexpr (has_fusion) {
                    if (use_gate) {
                        tmp_gate_o[t][i] = warp_reduce_sum<warp_size>(tmp_gate_o[t][i]);
                    }
                }
            }
        }
    }

    // Write results
    if (threadIdx.x < c_rows_per_block && (c_rows_per_block == 1 || uint32_t(row0 + threadIdx.x) < nrows_x)) {
        const uint32_t bias_idx = channel_x*stride_channel_dst + row0 + threadIdx.x;

        dst[channel_dst*stride_channel_dst + token_idx*stride_col_dst + row0 + threadIdx.x] =
            amb_moe_grouped_finish<type, has_fusion>(tmp[threadIdx.x], tmp_gate[threadIdx.x], use_gate,
                x_bias, gate_bias, x_scale, gate_scale, active_glu, glu_limit, channel_x, bias_idx);
#pragma unroll
        for (int t = 1; t < max_tokens; ++t) {
            if (others & (1u << t)) {
                dst[slot_of[t]*stride_channel_dst + uint32_t(t)*stride_col_dst + row0 + threadIdx.x] =
                    amb_moe_grouped_finish<type, has_fusion>(tmp_o[t][threadIdx.x], tmp_gate_o[t][threadIdx.x], use_gate,
                        x_bias, gate_bias, x_scale, gate_scale, active_glu, glu_limit, channel_x, bias_idx);
            }
        }
    }

    if constexpr (!has_fusion) {
        GGML_UNUSED_VARS(use_gate, tmp_gate, tmp_gate_o, vgate, x_bias, gate_bias, active_glu, glu_limit, x_scale, gate_scale);
    } else if constexpr (type != GGML_TYPE_NVFP4) {
        GGML_UNUSED_VARS(x_scale, gate_scale);
    }
}

template<ggml_type type>
static std::pair<dim3, dim3> calc_launch_params(
        const int ncols_dst, const int nrows_x, const int nchannels_dst, const int nsamples_or_ntokens,
        const int warp_size, const mmvq_parameter_table_id table_id, const bool small_k = false, const bool halve_iters = false) {
    const int nwarps = calc_nwarps(type, ncols_dst, table_id, small_k, halve_iters);
    const int rpb = calc_rows_per_block(type, ncols_dst, table_id, small_k, nwarps);
    const int64_t nblocks = (nrows_x + rpb - 1) / rpb;
    const dim3 block_nums(nblocks, nchannels_dst, nsamples_or_ntokens);
    const dim3 block_dims(warp_size, nwarps, 1);
    return {block_nums, block_dims};
}

// AMB_FUSE_SHEXP_MT (C20): weight types with multi-column fused MMVQ kernels (the shared-expert types of the
// target are q8_0 and q6_K); a short list keeps the extra instantiations few. Must match ggml_cuda_amb_mmvq_mt_type.
static constexpr __host__ __device__ bool amb_mmvq_mt_type(ggml_type type) {
    return type == GGML_TYPE_Q8_0 || type == GGML_TYPE_Q6_K || type == GGML_TYPE_Q5_K || type == GGML_TYPE_Q4_K;
}

bool ggml_cuda_amb_mmvq_mt_type(ggml_type type) {
    return amb_mmvq_mt_type(type);
}

template<ggml_type type, int c_ncols_dst, bool small_k = false, bool halve_iters = false>
static void mul_mat_vec_q_switch_fusion(
        const void * vx, const void * vy, const int32_t * ids, const ggml_cuda_mm_fusion_args_device fusion, float * dst,
        const uint32_t ncols_x, const uint3 nchannels_y, const uint32_t stride_row_x, const uint32_t stride_col_y,
        const uint32_t stride_col_dst, const uint3 channel_ratio, const uint32_t stride_channel_x,
        const uint32_t stride_channel_y, const uint32_t stride_channel_dst, const uint3 sample_ratio,
        const uint32_t stride_sample_x, const uint32_t stride_sample_y, const uint32_t stride_sample_dst,
        const dim3 & block_nums, const dim3 & block_dims, const int nbytes_shared,
        const uint32_t ids_stride, cudaStream_t stream) {

    const bool has_fusion = fusion.gate != nullptr || fusion.x_bias != nullptr || fusion.gate_bias != nullptr ||
                            fusion.x_scale != nullptr || fusion.gate_scale != nullptr;
    if constexpr (c_ncols_dst == 1) {
        if (has_fusion) {
            const ggml_cuda_kernel_launch_params launch_params = ggml_cuda_kernel_launch_params(block_nums, block_dims, nbytes_shared, stream);
            ggml_cuda_kernel_launch(mul_mat_vec_q<type, c_ncols_dst, true, small_k, halve_iters>, launch_params,
                 vx, vy, ids, fusion, dst, ncols_x, nchannels_y, stride_row_x, stride_col_y, stride_col_dst,
                 channel_ratio, stride_channel_x, stride_channel_y, stride_channel_dst,
                 sample_ratio, stride_sample_x, stride_sample_y, stride_sample_dst, ids_stride);
            return;
        }
    }

    // AMB_FUSE_SHEXP_MT (C20): multi-column fusions, only for the types amb_mmvq_mt_type lists
    if constexpr (c_ncols_dst > 1 && !small_k && !halve_iters && amb_mmvq_mt_type(type)) {
        const bool post = fusion.amb_post_sig != nullptr;
        if (has_fusion || post) {
            GGML_ASSERT(!(has_fusion && post));
            GGML_ASSERT(fusion.x_bias == nullptr && fusion.gate_bias == nullptr && fusion.shared_up == nullptr);
            const ggml_cuda_kernel_launch_params launch_params = ggml_cuda_kernel_launch_params(block_nums, block_dims, nbytes_shared, stream);
            if (post) {
                ggml_cuda_kernel_launch(mul_mat_vec_q<type, c_ncols_dst, false, false, false, true>, launch_params,
                     vx, vy, ids, fusion, dst, ncols_x, nchannels_y, stride_row_x, stride_col_y, stride_col_dst,
                     channel_ratio, stride_channel_x, stride_channel_y, stride_channel_dst,
                     sample_ratio, stride_sample_x, stride_sample_y, stride_sample_dst, ids_stride);
            } else {
                ggml_cuda_kernel_launch(mul_mat_vec_q<type, c_ncols_dst, true, false, false, false>, launch_params,
                     vx, vy, ids, fusion, dst, ncols_x, nchannels_y, stride_row_x, stride_col_y, stride_col_dst,
                     channel_ratio, stride_channel_x, stride_channel_y, stride_channel_dst,
                     sample_ratio, stride_sample_x, stride_sample_y, stride_sample_dst, ids_stride);
            }
            return;
        }
    }

    GGML_ASSERT(fusion.amb_post_sig == nullptr && "amb post-op fusion not instantiated for this type/ncols");
    GGML_ASSERT(!has_fusion && "fusion only supported for ncols_dst=1");

    const ggml_cuda_kernel_launch_params launch_params = ggml_cuda_kernel_launch_params(block_nums, block_dims, nbytes_shared, stream);
    ggml_cuda_kernel_launch(mul_mat_vec_q<type, c_ncols_dst, false, small_k, halve_iters>, launch_params,
        vx, vy, ids, fusion, dst, ncols_x, nchannels_y, stride_row_x, stride_col_y, stride_col_dst,
        channel_ratio, stride_channel_x, stride_channel_y, stride_channel_dst,
        sample_ratio, stride_sample_x, stride_sample_y, stride_sample_dst, ids_stride);
}

// AMB_MOE_MISS_OVERLAP=2 (C24): set by ggml_cuda_mul_mat_vec_q for the duration of one call whose ids are masked
// (GGML_TENSOR_FLAG_AMB_MASKED_IDS), read by mul_mat_vec_q_moe_launch (host only)
static thread_local bool ggml_cuda_amb_masked_ids = false;

// AMB_MOE_GROUPED (G1): switches, read once at the first multi-token MoE MMVQ launch
struct amb_moe_grouped_cfg {
    bool on        = false;
    int  check_max = 0;   // AMB_MOE_GROUPED_CHECK: number of calls that run both kernels and compare
    amb_moe_grouped_cfg() {
        const char * v = getenv("AMB_MOE_GROUPED");
        on = v != nullptr && strcmp(v, "1") == 0;
        if (v != nullptr && *v != '\0' && strcmp(v, "0") != 0 && !on) {
            GGML_LOG_WARN("amb: AMB_MOE_GROUPED=%s ignored (the only value is 1)\n", v);
        }
        if (const char * c = getenv("AMB_MOE_GROUPED_CHECK"); on && c != nullptr && atoi(c) > 0) {
            check_max = atoi(c) == 1 ? 256 : atoi(c);
        }
        if (on) {
            GGML_LOG_INFO("amb: AMB_MOE_GROUPED=1 active (MoE MMVQ, 2..%d tokens, types nvfp4 and q8_0: an expert selected by "
                    "several tokens of the batch is read by one warp, which computes all of them; bit-identical)%s\n",
                    MMVQ_MAX_BATCH_SIZE, check_max > 0 ? "; AMB_MOE_GROUPED_CHECK: the stock kernel runs first and the outputs are compared" : "");
        }
    }
};

static const amb_moe_grouped_cfg & amb_moe_grouped() {
    static const amb_moe_grouped_cfg cfg;
    return cfg;
}

// AMB_MOE_GROUPED_CHECK: host copy of the float range [0, n) of a device buffer (synchronizes the stream)
static void amb_moe_grouped_read(std::vector<float> & out, const float * src, const size_t n, cudaStream_t stream) {
    out.resize(n);
    CUDA_CHECK(cudaStreamSynchronize(stream));
    CUDA_CHECK(cudaMemcpy(out.data(), src, n*sizeof(float), cudaMemcpyDeviceToHost));
}

static void amb_moe_grouped_diff(const std::vector<float> & a, const std::vector<float> & b, double & max_abs, int64_t & n_bits) {
    GGML_ASSERT(a.size() == b.size());
    for (size_t i = 0; i < a.size(); i++) {
        if (memcmp(&a[i], &b[i], sizeof(float)) != 0) {
            n_bits++;
            const double d = fabs((double) a[i] - (double) b[i]);
            // a NaN on one side only counts as an infinite difference
            max_abs = std::max(max_abs, d == d ? d : (double) INFINITY);
        }
    }
}

template <ggml_type type>
static void mul_mat_vec_q_moe_launch(
        const void * vx, const void * vy, const int32_t * ids, const ggml_cuda_mm_fusion_args_device fusion, float * dst,
        const uint32_t ncols_x, const uint3 nchannels_y, const uint32_t nrows_x,
        const uint32_t stride_row_x, const uint32_t stride_col_y, const uint32_t stride_col_dst,
        const uint32_t stride_channel_x, const uint32_t stride_channel_y, const uint32_t stride_channel_dst,
        const uint32_t ncols_dst, const uint32_t ids_stride,
        const int warp_size, const int nchannels_dst, cudaStream_t stream) {

    constexpr int rows_per_block = 2; // 2 gives best perf based on tuning
    const int64_t nblocks_rows = (nrows_x + rows_per_block - 1) / rows_per_block;
    const dim3 block_nums(nblocks_rows, nchannels_dst + (fusion.shared_up != nullptr));
    const dim3 block_dims(warp_size, ncols_dst);
    const ggml_cuda_kernel_launch_params launch_params = ggml_cuda_kernel_launch_params(block_nums, block_dims, 0, stream);

    const bool has_fusion = fusion.gate != nullptr || fusion.x_bias != nullptr || fusion.gate_bias != nullptr ||
                            fusion.x_scale != nullptr || fusion.gate_scale != nullptr;

    // AMB_MOE_MISS_OVERLAP=2 (C24): masked ids take their own instantiations, chosen here on the host; the launches
    // below the branch are the ones of before
    if (ggml_cuda_amb_masked_ids) {
        GGML_ASSERT(fusion.shared_up == nullptr && "masked ids with a fused shared expert");
        if (has_fusion) {
            ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, rows_per_block, true, true>, launch_params,
                vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                stride_row_x, stride_col_y, stride_col_dst,
                stride_channel_x, stride_channel_y, stride_channel_dst,
                ncols_dst, ids_stride);
        } else {
            ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, rows_per_block, false, true>, launch_params,
                vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                stride_row_x, stride_col_y, stride_col_dst,
                stride_channel_x, stride_channel_y, stride_channel_dst,
                ncols_dst, ids_stride);
        }
        return;
    }

    // AMB_MOE_DOWN_RPB=N / AMB_MOE_UP_RPB=N (M5, default off; N in 1, 4, 8, 16; 2 is the stock value): rows per block of
    // this launch. DOWN applies to the calls whose rows are shorter than the row count (the down projection: 2304 rows
    // of 1152 weights), UP to the others (gate_up: 2304 x 2304). Each row is still summed by one warp over the same
    // block sequence and reduced the same way, so the outputs are bit-identical; only the grid changes
    // ((nrows / N) x routes blocks of the same warp x token shape). AMB_MOE_RPB_CHECK=K: the first K such launches
    // outside a CUDA graph capture run the stock launch first and compare the outputs bit by bit.
    {
        struct amb_rpb_cfg {
            int down = 0, up = 0, check = 0;
            amb_rpb_cfg() {
                auto get = [](const char * name) {
                    const char * v = getenv(name);
                    const int n = v != nullptr ? atoi(v) : 0;
                    if (v != nullptr && n != 0 && n != 1 && n != 2 && n != 4 && n != 8 && n != 16) {
                        GGML_LOG_WARN("amb_moe_rpb: %s=%s ignored (1, 2, 4, 8 or 16)\n", name, v);
                        return 0;
                    }
                    return n == 2 ? 0 : n;
                };
                down = get("AMB_MOE_DOWN_RPB");
                up   = get("AMB_MOE_UP_RPB");
                if (const char * c = getenv("AMB_MOE_RPB_CHECK"); c != nullptr && atoi(c) > 0) {
                    check = atoi(c);
                }
            }
        };
        static const amb_rpb_cfg rcfg;
        const bool is_down = nrows_x > ncols_x;
        const int  rpb     = is_down ? rcfg.down : rcfg.up;
        if (rpb != 0 && fusion.shared_up == nullptr && nrows_x % (uint32_t) rpb == 0) {
            const dim3 block_nums_r(nrows_x / rpb, nchannels_dst);
            const ggml_cuda_kernel_launch_params lp = ggml_cuda_kernel_launch_params(block_nums_r, block_dims, 0, stream);
            const auto launch_rpb = [&] {
#define AMB_RPB_LAUNCH(N)                                                                                        \
                if (has_fusion) {                                                                                \
                    ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, N, true>, lp,                                \
                        vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,                                 \
                        stride_row_x, stride_col_y, stride_col_dst,                                              \
                        stride_channel_x, stride_channel_y, stride_channel_dst,                                  \
                        ncols_dst, ids_stride);                                                                  \
                } else {                                                                                         \
                    ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, N, false>, lp,                               \
                        vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,                                 \
                        stride_row_x, stride_col_y, stride_col_dst,                                              \
                        stride_channel_x, stride_channel_y, stride_channel_dst,                                  \
                        ncols_dst, ids_stride);                                                                  \
                }
                switch (rpb) {
                    case 1:  { AMB_RPB_LAUNCH(1)  } break;
                    case 4:  { AMB_RPB_LAUNCH(4)  } break;
                    case 8:  { AMB_RPB_LAUNCH(8)  } break;
                    default: { AMB_RPB_LAUNCH(16) } break;
                }
#undef AMB_RPB_LAUNCH
            };
            static uint64_t n_taken[2] = { 0, 0 }, n_next_log = 1;
            static int      n_checked = 0, n_check_skipped = 0;
            static int64_t  check_bits = 0;
            n_taken[is_down ? 0 : 1]++;
            bool done = false;
            if (rcfg.check > 0 && n_checked < rcfg.check) {
                cudaStreamCaptureStatus cap = cudaStreamCaptureStatusNone;
                CUDA_CHECK(cudaStreamIsCapturing(stream, &cap));
                const size_t n_dst = (size_t) (nchannels_dst - 1)*stride_channel_dst + (size_t) (ncols_dst - 1)*stride_col_dst + nrows_x;
                if (cap == cudaStreamCaptureStatusNone) {
                    std::vector<float> ref, got;
                    if (has_fusion) {
                        ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, rows_per_block, true>, launch_params,
                            vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                            stride_row_x, stride_col_y, stride_col_dst,
                            stride_channel_x, stride_channel_y, stride_channel_dst,
                            ncols_dst, ids_stride);
                    } else {
                        ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, rows_per_block, false>, launch_params,
                            vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                            stride_row_x, stride_col_y, stride_col_dst,
                            stride_channel_x, stride_channel_y, stride_channel_dst,
                            ncols_dst, ids_stride);
                    }
                    amb_moe_grouped_read(ref, dst, n_dst, stream);
                    if (n_dst == (size_t) nchannels_dst*ncols_dst*nrows_x) {
                        CUDA_CHECK(cudaMemsetAsync(dst, 0xFF, n_dst*sizeof(float), stream)); // an unwritten value shows up
                    }
                    launch_rpb();
                    amb_moe_grouped_read(got, dst, n_dst, stream);
                    double  max_abs = 0.0;
                    int64_t n_bits  = 0;
                    amb_moe_grouped_diff(ref, got, max_abs, n_bits);
                    n_checked++;
                    check_bits += n_bits;
                    GGML_LOG_INFO("amb_moe_rpb: check %d/%d: %s %s rows=%u cols=%u tokens=%u routes=%d rows/block=%d fusion=%d: "
                        "%lld of %zu values differ in bits, max |diff| = %g%s\n", n_checked, rcfg.check, ggml_type_name(type),
                        is_down ? "down" : "up", nrows_x, ncols_x, ncols_dst, nchannels_dst, rpb, has_fusion ? 1 : 0,
                        (long long) n_bits, ref.size(), max_abs, n_bits == 0 ? " (bit-identical)" : " (MISMATCH)");
                    done = true;
                } else {
                    n_check_skipped++;
                }
            }
            if (!done) {
                launch_rpb();
            }
            if (n_taken[0] + n_taken[1] >= n_next_log) {
                GGML_LOG_INFO("amb_moe_rpb: active: AMB_MOE_DOWN_RPB=%d AMB_MOE_UP_RPB=%d (0 = stock 2): %llu down and %llu up "
                    "launches with their own rows per block so far (last: %s rows=%u cols=%u, grid %u x %d); check: %d compared, "
                    "%lld values differ in bits, %d skipped inside a graph capture\n", rcfg.down, rcfg.up,
                    (unsigned long long) n_taken[0], (unsigned long long) n_taken[1], is_down ? "down" : "up", nrows_x, ncols_x,
                    nrows_x / rpb, nchannels_dst, n_checked, (long long) check_bits, n_check_skipped);
                n_next_log *= 4;
            }
            return;
        }
    }

    const auto launch_stock = [&] {
        if (has_fusion) {
            ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, rows_per_block, true>, launch_params,
                vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                stride_row_x, stride_col_y, stride_col_dst,
                stride_channel_x, stride_channel_y, stride_channel_dst,
                ncols_dst, ids_stride);
        } else {
            ggml_cuda_kernel_launch(mul_mat_vec_q_moe<type, rows_per_block, false>, launch_params,
                vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                stride_row_x, stride_col_y, stride_col_dst,
                stride_channel_x, stride_channel_y, stride_channel_dst,
                ncols_dst, ids_stride);
        }
    };

    // AMB_MOE_GROUPED (G1): the expert-grouped kernel for the types it is instantiated for; everything else (other
    // types, masked ids above, more than 64 routes) keeps the stock launch
    if constexpr (amb_moe_grouped_type(type)) {
        const amb_moe_grouped_cfg & g = amb_moe_grouped();
        const bool grouped = g.on && fusion.amb_x_scale_ids == nullptr && warp_size == 32 && ncols_dst >= 2 && ncols_dst <= MMVQ_MAX_BATCH_SIZE &&
                             nchannels_dst >= 1 && (int64_t) nchannels_dst*ncols_dst <= 64;
        if (grouped) {
            const auto launch_grouped = [&] {
                if (has_fusion) {
                    ggml_cuda_kernel_launch(mul_mat_vec_q_moe_grouped<type, rows_per_block, true>, launch_params,
                        vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                        stride_row_x, stride_col_y, stride_col_dst,
                        stride_channel_x, stride_channel_y, stride_channel_dst,
                        ncols_dst, ids_stride);
                } else {
                    ggml_cuda_kernel_launch(mul_mat_vec_q_moe_grouped<type, rows_per_block, false>, launch_params,
                        vx, vy, ids, fusion, dst, ncols_x, nchannels_y, nrows_x,
                        stride_row_x, stride_col_y, stride_col_dst,
                        stride_channel_x, stride_channel_y, stride_channel_dst,
                        ncols_dst, ids_stride);
                }
            };

            static int      n_checked    = 0;
            static double   check_max    = 0.0;
            static int64_t  check_bits   = 0;
            static int64_t  check_routes = 0;
            static int64_t  check_groups = 0;
            if (n_checked >= g.check_max) {
                launch_grouped();
                return;
            }

            // AMB_MOE_GROUPED_CHECK: stock kernel first, its output saved on the host, the output range filled with
            // NaN bits (so a position the grouped kernel does not write shows up), then the grouped kernel
            const size_t n_dst    = (size_t) (nchannels_dst - 1)*stride_channel_dst + (size_t) (ncols_dst - 1)*stride_col_dst + nrows_x;
            const bool   dense    = n_dst == (size_t) nchannels_dst*ncols_dst*nrows_x;
            const size_t n_shared = fusion.shared_up ? (size_t) (ncols_dst - 1)*fusion.shared_stride_col_dst + nrows_x : 0;
            const bool   dense_sh = n_shared == (size_t) ncols_dst*nrows_x;

            std::vector<float> ref, ref_sh, got, got_sh;
            launch_stock();
            amb_moe_grouped_read(ref, dst, n_dst, stream);
            if (n_shared > 0) {
                amb_moe_grouped_read(ref_sh, fusion.shared_dst, n_shared, stream);
            }
            if (dense) {
                CUDA_CHECK(cudaMemsetAsync(dst, 0xFF, n_dst*sizeof(float), stream));
            }
            if (n_shared > 0 && dense_sh) {
                CUDA_CHECK(cudaMemsetAsync(fusion.shared_dst, 0xFF, n_shared*sizeof(float), stream));
            }
            launch_grouped();
            amb_moe_grouped_read(got, dst, n_dst, stream);
            if (n_shared > 0) {
                amb_moe_grouped_read(got_sh, fusion.shared_dst, n_shared, stream);
            }

            // routes and distinct ids of this call
            std::vector<int32_t> ids_h((size_t) (ncols_dst - 1)*ids_stride + nchannels_dst);
            CUDA_CHECK(cudaMemcpy(ids_h.data(), ids, ids_h.size()*sizeof(int32_t), cudaMemcpyDeviceToHost));
            std::vector<int32_t> sel;
            for (uint32_t t = 0; t < ncols_dst; t++) {
                for (int c = 0; c < nchannels_dst; c++) {
                    sel.push_back(ids_h[c + (size_t) t*ids_stride]);
                }
            }
            const int n_routes = (int) sel.size();
            std::sort(sel.begin(), sel.end());
            const int n_groups = (int) (std::unique(sel.begin(), sel.end()) - sel.begin());

            double  max_abs = 0.0;
            int64_t n_bits  = 0;
            amb_moe_grouped_diff(ref, got, max_abs, n_bits);
            amb_moe_grouped_diff(ref_sh, got_sh, max_abs, n_bits);
            n_checked++;
            check_max     = std::max(check_max, max_abs);
            check_bits   += n_bits;
            check_routes += n_routes;
            check_groups += n_groups;
            if (n_checked <= 8 || n_bits != 0) {
                GGML_LOG_INFO("amb: AMB_MOE_GROUPED_CHECK call %d: type=%s tokens=%u slots=%d rows=%u cols=%u fusion=%d shared=%d "
                        "routes=%d distinct=%d nan_fill=%d: max_abs_diff=%g, %lld of %zu values differ in bits%s\n",
                        n_checked, ggml_type_name(type), ncols_dst, nchannels_dst, nrows_x, ncols_x, has_fusion ? 1 : 0,
                        fusion.shared_up ? 1 : 0, n_routes, n_groups, dense ? 1 : 0, max_abs, (long long) n_bits,
                        ref.size() + ref_sh.size(), n_bits == 0 ? "" : " (MISMATCH)");
            }
            if (n_checked == g.check_max) {
                GGML_LOG_INFO("amb: AMB_MOE_GROUPED_CHECK done: %d calls, max_abs_diff=%g, %lld values differ in bits, "
                        "%.2f routes and %.2f distinct experts per call -> %s\n",
                        n_checked, check_max, (long long) check_bits, (double) check_routes/n_checked,
                        (double) check_groups/n_checked, check_bits == 0 ? "OK (bit-identical)" : "MISMATCH");
            }
            return;
        }
    }

    launch_stock();
}

template <ggml_type type>
static void mul_mat_vec_q_switch_ncols_dst(
        const void * vx, const void * vy, const int32_t * ids, const ggml_cuda_mm_fusion_args_device fusion, float * dst,
        const int ncols_x, const int nrows_x, const int ncols_dst,
        const int stride_row_x, const int stride_col_y, const int stride_col_dst,
        const int nchannels_x, const int nchannels_y, const int nchannels_dst,
        const int stride_channel_x, const int stride_channel_y, const int stride_channel_dst,
        const int nsamples_x, const int nsamples_dst, const int stride_sample_x, const int stride_sample_y, const int stride_sample_dst,
        const int ids_stride, cudaStream_t stream) {

    GGML_ASSERT(ncols_x % ggml_blck_size(type) == 0);
    GGML_ASSERT(ncols_dst <= MMVQ_MAX_BATCH_SIZE);

    const uint3 nchannels_y_fd   = ids ? init_fastdiv_values(nchannels_y) : make_uint3(0, 0, 0);
    const uint3 channel_ratio_fd = ids ? make_uint3(0, 0, 0)              : init_fastdiv_values(nchannels_dst / nchannels_x);
    const uint3 sample_ratio_fd  = init_fastdiv_values(nsamples_dst  / nsamples_x);

    const int device = ggml_cuda_get_device();
    const int                     cc        = ggml_cuda_info().devices[device].cc;
    const int warp_size = ggml_cuda_info().devices[device].warp_size;
    const mmvq_parameter_table_id table_id  = get_device_table_id(cc);

    const bool has_ids = ids != nullptr;

    // How the K loop divides up at the baseline block width, both decisions below use these.
    constexpr int qk                    = ggml_cuda_type_traits<type>::qk;
    constexpr int qi                    = ggml_cuda_type_traits<type>::qi;
    constexpr int vdr                   = get_vdr_mmvq(type);
    const int     blocks_per_row_x      = ncols_x / qk;
    const int     blocks_per_iter_1warp = vdr * warp_size / qi;

    const auto should_use_small_k = [&](int c_ncols_dst) {
        // When K is small, increase rows_per_block to match nwarps so each warp has more work to do
        // Trigger when the full thread block covers all K blocks in a single loop iteration and few threads remain idle.
        const int  nwarps = calc_nwarps(type, c_ncols_dst, table_id);
        bool       use    = nwarps > 1 && blocks_per_row_x < nwarps * blocks_per_iter_1warp;

        constexpr std::array<ggml_type, 2> iq_slow_turing = {
            GGML_TYPE_IQ3_XXS,
            GGML_TYPE_IQ3_S,
        };
        constexpr std::array<ggml_type, 11> iq_slow_other = {
            GGML_TYPE_IQ1_S,   GGML_TYPE_IQ1_M,    GGML_TYPE_IQ2_XXS, GGML_TYPE_IQ2_XS,
            GGML_TYPE_IQ2_S,   GGML_TYPE_IQ3_XXS,  GGML_TYPE_IQ3_S,   GGML_TYPE_IQ4_XS,
            GGML_TYPE_IQ1_XS,  GGML_TYPE_IQ1_XXS,  GGML_TYPE_IQ1_XXXS,
        };
        constexpr std::array<ggml_type, 3> slow_pascal = {
            GGML_TYPE_IQ3_S,
            GGML_TYPE_Q2_K,
            GGML_TYPE_Q3_K,
        };

        const bool is_nvidia_turing_plus  = GGML_CUDA_CC_IS_NVIDIA(cc) && cc >= GGML_CUDA_CC_TURING;
        const bool is_nvidia_pascal_older = GGML_CUDA_CC_IS_NVIDIA(cc) && cc < GGML_CUDA_CC_VOLTA;

        if (is_nvidia_turing_plus) {
            if (ncols_dst == 1 &&
                    std::find(iq_slow_turing.begin(), iq_slow_turing.end(), type) != iq_slow_turing.end()) {
                use = false;
            }
        } else if ((ncols_dst == 1 && std::find(iq_slow_other.begin(), iq_slow_other.end(), type) != iq_slow_other.end()) ||
                (is_nvidia_pascal_older && std::find(slow_pascal.begin(), slow_pascal.end(), type) != slow_pascal.end()) ||
                GGML_CUDA_CC_IS_RDNA(cc)) {
            use = false;
        }

        return use;
    };

    // Whether doubling nwarps pays off on the ncols_dst == 1 path, where K sets the K loop trip count.
    const auto should_halve_iters = [&] {
        if (table_id != MMVQ_PARAMETERS_GB10) {
            return false;
        }

        // Expert rows are gathered per token, so a wider block adds reduction work without reuse.
        if (has_ids) {
            return false;
        }

        const int blocks_per_iter = calc_nwarps(type, 1, table_id) * blocks_per_iter_1warp;
        const int iters           = (blocks_per_row_x + blocks_per_iter - 1) /  blocks_per_iter;
        const int iters_wide      = (blocks_per_row_x + blocks_per_iter * 2 - 1) / (blocks_per_iter * 2);

        // An odd trip count leaves half the wider block idle for its last iteration, that tail is
        // only affordable once the loop is long enough to dilute it to an eighth of the work (observation).
        const int idle = iters_wide * 2 - iters;

        return idle * 8 <= iters_wide * 2;
    };

    if (has_ids && ncols_dst > 1) {
        // Multi-token MUL_MAT_ID path - dedicated MoE kernel
        mul_mat_vec_q_moe_launch<type>(
            vx, vy, ids, fusion, dst, ncols_x, nchannels_y_fd, nrows_x,
            stride_row_x, stride_col_y, stride_col_dst,
            stride_channel_x, stride_channel_y, stride_channel_dst,
            ncols_dst, ids_stride, warp_size, nchannels_dst, stream);
        return;
    }

    switch (ncols_dst) {
        case 1: {
            // static, else MSVC lambda capture breaks the constexpr uses below
            static constexpr int c_ncols_dst = 1;

            // Tag types keep the flags compile-time, so __launch_bounds__ matches what is launched.
            const auto launch = [&](auto small_k_tag, auto halve_iters_tag) {
                constexpr bool c_small_k = decltype(small_k_tag)::value;
                // Types the table does not promote would compile a second, identical kernel.
                constexpr bool c_promoted =
                    calc_nwarps(type, c_ncols_dst, MMVQ_PARAMETERS_GB10, false, true) !=
                    calc_nwarps(type, c_ncols_dst, MMVQ_PARAMETERS_GB10, false, false);

                constexpr bool c_halve_iters = decltype(halve_iters_tag)::value && c_promoted;

                const std::pair<dim3, dim3> dims = calc_launch_params<type>(c_ncols_dst, nrows_x, nchannels_dst + (fusion.shared_up != nullptr),
                                                                              nsamples_dst, warp_size, table_id, c_small_k, c_halve_iters);
                mul_mat_vec_q_switch_fusion<type, c_ncols_dst, c_small_k, c_halve_iters>(
                    vx, vy, ids, fusion, dst, ncols_x, nchannels_y_fd, stride_row_x, stride_col_y, stride_col_dst,
                    channel_ratio_fd, stride_channel_x, stride_channel_y, stride_channel_dst, sample_ratio_fd,
                    stride_sample_x, stride_sample_y, stride_sample_dst, dims.first, dims.second, 0, ids_stride,
                    stream);
            };

            if (should_use_small_k(c_ncols_dst)) {
                launch(std::true_type{},  std::false_type{});
            } else if (should_halve_iters()) {
                launch(std::false_type{}, std::true_type{});
            } else {
                launch(std::false_type{}, std::false_type{});
            }
        } break;
        case 2: {
            constexpr int c_ncols_dst = 2;
            std::pair<dim3, dim3> dims = calc_launch_params<type>(c_ncols_dst, nrows_x, nchannels_dst, nsamples_dst, warp_size, table_id);
            mul_mat_vec_q_switch_fusion<type, c_ncols_dst>(vx, vy, ids, fusion, dst, ncols_x, nchannels_y_fd, stride_row_x, stride_col_y, stride_col_dst,
                 channel_ratio_fd, stride_channel_x, stride_channel_y, stride_channel_dst,
                 sample_ratio_fd, stride_sample_x, stride_sample_y, stride_sample_dst,
                 dims.first, dims.second, 0, ids_stride, stream);
        } break;
        case 3: {
            constexpr int c_ncols_dst = 3;
            std::pair<dim3, dim3> dims = calc_launch_params<type>(c_ncols_dst, nrows_x, nchannels_dst, nsamples_dst, warp_size, table_id);
            mul_mat_vec_q_switch_fusion<type, c_ncols_dst>(vx, vy, ids, fusion, dst, ncols_x, nchannels_y_fd, stride_row_x, stride_col_y, stride_col_dst,
